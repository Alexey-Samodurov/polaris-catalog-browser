#!/usr/bin/env python3
"""Lists the third-party jars inside the built plugin zip with their licenses, as THIRD-PARTY.md.

Run after `./gradlew :plugin:buildPlugin`:  python3 -I scripts/third-party.py > THIRD-PARTY.md
Licenses come from each artifact's POM in the Gradle cache, following parent POMs; artifacts whose
POM names none fall back to their project's known license, and anything unknown is marked TODO.
"""
import glob
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.expanduser("~/.gradle/caches/modules-2/files-2.1")
OWN = ("plugin-", "polaris-client-", "polaris-preview-")
# Projects whose POMs inherit the license from a parent that may not be cached.
KNOWN = {
    "org.apache.": "Apache License, Version 2.0",
    "software.amazon.": "Apache License, Version 2.0",
}


def pom_licenses(pom, depth=0):
    text = open(pom, errors="ignore").read()
    names = re.findall(r"<license>.*?<name>\s*(.*?)\s*</name>", text, re.S)
    if names or depth > 4:
        return names
    parent = re.search(r"<parent>.*?<groupId>(.*?)</groupId>.*?<artifactId>(.*?)</artifactId>.*?<version>(.*?)</version>", text, re.S)
    if not parent:
        return []
    g, a, v = parent.groups()
    for p in glob.glob(f"{CACHE}/{g}/{a}/{v}/*/{a}-{v}.pom"):
        return pom_licenses(p, depth + 1)
    return []


def main():
    zips = glob.glob(os.path.join(ROOT, "plugin/build/distributions/*.zip"))
    if not zips:
        sys.exit("build the plugin first: ./gradlew :plugin:buildPlugin")
    jars = sorted(os.path.basename(n) for n in zipfile.ZipFile(zips[0]).namelist()
                  if n.endswith(".jar") and not os.path.basename(n).startswith(OWN))
    where = {}
    for root, _, files in os.walk(CACHE):
        for f in files:
            if f.endswith(".jar"):
                where.setdefault(f, root)
    rows = []
    for jar in jars:
        root = where.get(jar)
        if root is None:
            rows.append((jar, "TODO"))
            continue
        g, a, v = root.split("/files-2.1/")[1].split("/")[:3]
        poms = glob.glob(f"{CACHE}/{g}/{a}/{v}/*/{a}-{v}.pom")
        names = list(dict.fromkeys(n.strip() for n in (pom_licenses(poms[0]) if poms else [])))
        license = "; ".join(names) or next((l for p, l in KNOWN.items() if g.startswith(p)), "TODO")
        rows.append((f"{g}:{a}:{v}", license))
    print("# Third-party software\n")
    print("The plugin bundles the following libraries, each under its own license.")
    print("Generated by `scripts/third-party.py` from the built plugin.\n")
    print("| Artifact | License |")
    print("| --- | --- |")
    for artifact, license in sorted(rows):
        print(f"| `{artifact}` | {license} |")


main()
